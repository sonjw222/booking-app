-- ============================================================
-- 센터 종목(카테고리) — 홈 화면 종목 필터용
--
-- 하는 일:
--   centers 에 category 컬럼 추가
--   → 홈에서 "필라테스" 누르면 필라테스 센터 수업만 필터
--   → 매니저가 센터 정보에서 종목 지정
--
-- 파일 전체를 SQL Editor에 붙여넣고 Run 하세요. 여러 번 실행해도 안전.
-- ============================================================

alter table centers add column if not exists category text;


-- ============================================================
-- 확인
-- ============================================================
select column_name from information_schema.columns
where table_name = 'centers' and column_name = 'category';


