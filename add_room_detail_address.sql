-- ============================================================
-- 룸 상세주소 컬럼 추가
--
-- 배경: 룸(rooms) 관리 화면에 "도로명 주소 검색 + 상세주소" 기능을 추가하면서,
-- 상세주소(건물명/층/호수 등)를 기존 address(도로명주소) 컬럼과 합쳐서 저장하지
-- 않기로 했다 — 기존 address 컬럼은 이 기능 추가 전까지 사용자가 자유 형식으로
-- 직접 입력해온 값이라(도로명주소 형식이 아닐 수 있음), 나중에 편집 시 "도로명주소"
-- 와 "상세주소"를 다시 안전하게 분리할 방법이 없다(구분자 concat은 손실 가능성이
-- 있어 이 프로젝트 정책상 선택하지 않음). 그래서 완전히 분리된 새 컬럼을 추가한다.
--
-- 이 컬럼은 좌표(latitude/longitude)와 독립적이다 — 상세주소를 수정해도 좌표는
-- 절대 바뀌지 않는다(lib/rooms.ts, app/manager/rooms/page.tsx 참고).
--
-- 적용 전 주의: lib/rooms.ts의 fetchRooms/addRoom/updateRoom은 이 컬럼이 없어도
-- (Postgres 42703) 자동으로 detail_address 없이 재시도하도록 방어 처리가 되어
-- 있어 기존 룸 조회/저장 자체가 깨지지는 않는다 — 다만 상세주소 입력/표시 기능은
-- 이 migration을 실행하기 전까지 항상 비어있는 것으로 저장된다.
--
-- 파일 전체를 SQL Editor에 붙여넣고 Run 하세요. 여러 번 실행해도 안전.
-- 이 세션에서는 production에 실행하지 않았습니다 — 사용자 승인 후 직접 실행하세요.
-- ============================================================

alter table rooms add column if not exists detail_address text;

comment on column rooms.detail_address is
  '상세주소(건물명/층/호수 등, 선택). address(도로명주소)와 별개로 보관 — 사용자가
   직접 입력한 값만 들어가며, 좌표(latitude/longitude)나 address 값에 영향을 주지
   않는다. 기존 GRANT(anon/authenticated/service_role)는 테이블 단위라 새 컬럼에도
   그대로 적용되고, RLS도 행 단위 정책이라 추가 정책이 필요 없다.';

-- ============================================================
-- 확인
-- ============================================================
select column_name, data_type from information_schema.columns
where table_name = 'rooms' order by ordinal_position;

