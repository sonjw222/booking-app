-- ============================================================
-- 반복수업 그룹 관리
--
-- 하는 일:
--   classes 에 recurring_group_id 컬럼 추가
--   → 반복 등록으로 만든 수업들을 같은 그룹으로 묶어,
--     수정/삭제 시 "전체에 적용" 가능
--   → 기존 단발 수업은 null (영향 없음)
--
-- 파일 전체를 SQL Editor에 붙여넣고 Run 하세요. 여러 번 실행해도 안전.
-- ============================================================

alter table classes add column if not exists recurring_group_id uuid;

-- (선택) 그룹 조회 성능용 인덱스
create index if not exists idx_classes_recurring_group on classes(recurring_group_id);


-- ============================================================
-- 확인
-- ============================================================
select column_name from information_schema.columns
where table_name = 'classes' and column_name = 'recurring_group_id';


